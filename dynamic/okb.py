#!/usr/bin/python3
"""
Onboard dynamic top row.

Generates one Onboard layout per profile in ~/.config/onboard-dynamic/rows.toml
(identical to the base layout except for the half-height top row) and, in
`watch` mode, switches Onboard between them based on the focused window --
and, for terminals, on what is running inside (shell / tmux / nvim ...).

Usage:
    okb.py generate     regenerate layouts + key action scripts
    okb.py watch        run the focus watcher (autostarted at login)
    okb.py status       print which profile the focused window maps to
"""
import fcntl
import glob
import hashlib
import json
import os
import re
import selectors
import shlex
import subprocess
import sys
import time
import tomllib
from xml.sax.saxutils import escape, quoteattr

HOME = os.path.expanduser("~")
CONFIG = os.path.join(HOME, ".config/onboard-dynamic/rows.toml")
ROOT = os.path.join(HOME, ".local/share/onboard/dynamic")
GEN_DIR = os.path.join(ROOT, "generated")
ACT_DIR = os.path.join(ROOT, "actions")   # on sys.path via a .pth file
STATE = os.path.join(GEN_DIR, "index.json")
LOG = os.path.join(HOME, ".cache/onboard-dynamic.log")
LOCK = os.path.join(HOME, ".cache/onboard-dynamic.lock")

# half-height row geometry (logical SVG units, matches Small (Custom)-Alpha.svg)
ROW_X0, ROW_X1 = 0.63, 293.37
ROW_Y, ROW_H = -12.87, 10.74
GAP = 1.26
LABEL_MARGIN = "1.5, 0.75"
CHAR_W, PAD_W, MIN_W = 4.6, 6.0, 12.0

HALF_ROW_RE = re.compile(
    r'(<!-- half-height top row[^>]*-->\s*)<panel filename="[^"]*">.*?</panel>',
    re.S)


def log(*a):
    msg = time.strftime("%H:%M:%S ") + " ".join(str(x) for x in a)
    print(msg, flush=True)


# ------------------------------------------------------------------ config

def load_config():
    with open(CONFIG, "rb") as f:
        cfg = tomllib.load(f)
    cfg.setdefault("settings", {})
    cfg.setdefault("rules", [])
    cfg.setdefault("terminal", {})
    cfg.setdefault("profiles", {})
    return cfg


def resolve_keys(profiles, name, seen=()):
    if name in seen:
        raise ValueError(f"include cycle at profile '{name}'")
    p = profiles.get(name)
    if p is None:
        raise ValueError(f"unknown profile '{name}'")
    keys = []
    for inc in p.get("include", []):
        keys += resolve_keys(profiles, inc, seen + (name,))
    keys += p.get("keys", [])
    return keys


def base_layout_path(cfg):
    return os.path.expanduser(cfg["settings"].get(
        "base_layout",
        "~/.local/share/onboard/layouts/Small (Custom).onboard"))


# -------------------------------------------------------------- generation

def action_module(key):
    """Write (if needed) a tiny module Onboard imports for a script key."""
    seq = key.get("keys", "").split()
    text = key.get("type")
    parts = []
    if seq:
        parts.append("xdotool key --clearmodifiers " +
                     " ".join(shlex.quote(k) for k in seq))
    if text:
        parts.append("xdotool type --clearmodifiers -- " + shlex.quote(text))
    if not parts:
        raise ValueError(f"key {key!r} has neither 'keys' nor 'type'")
    cmd = " && ".join(parts)
    name = "okb_" + hashlib.sha1(cmd.encode()).hexdigest()[:12]
    path = os.path.join(ACT_DIR, name + ".py")
    if not os.path.exists(path):
        with open(path, "w") as f:
            f.write("# generated by okb.py -- " + cmd.replace("\n", " ") + "\n"
                    "import subprocess\n"
                    f"CMD = {['sh', '-c', cmd]!r}\n"
                    "def run():\n"
                    "    subprocess.Popen(CMD, start_new_session=True,\n"
                    "                     stdin=subprocess.DEVNULL,\n"
                    "                     stdout=subprocess.DEVNULL,\n"
                    "                     stderr=subprocess.DEVNULL)\n")
    return name


def row_geometry(labels):
    natural = [max(MIN_W, PAD_W + CHAR_W * len(l)) for l in labels]
    space = (ROW_X1 - ROW_X0) - GAP * (len(labels) - 1)
    scale = space / sum(natural)
    xs, x = [], ROW_X0
    for w in natural:
        w *= scale
        xs.append((x, w))
        x += w + GAP
    return xs, scale


def generate(cfg=None):
    cfg = cfg or load_config()
    os.makedirs(GEN_DIR, exist_ok=True)
    os.makedirs(ACT_DIR, exist_ok=True)
    base = base_layout_path(cfg)
    base_dir = os.path.dirname(base)
    with open(base, encoding="utf-8") as f:
        src = f.read()
    if not HALF_ROW_RE.search(src):
        raise RuntimeError("half-height top row panel not found in " + base)
    # make the base layout's SVG references absolute
    src = re.sub(r'filename="(?!/)([^"]+\.svg)"',
                 lambda m: 'filename=' + quoteattr(os.path.join(base_dir, m.group(1))),
                 src)

    # include the base SVGs in the hash so geometry edits force a reload
    svg_digest = hashlib.sha1()
    for p in sorted(glob.glob(os.path.join(base_dir, "*.svg"))):
        with open(p, "rb") as f:
            svg_digest.update(f.read())
    src_key = src + svg_digest.hexdigest()

    index, keep = {}, set()
    for name in cfg["profiles"]:
        keys = resolve_keys(cfg["profiles"], name)
        labels = ["Esc"] + [k["label"] for k in keys]
        geo, scale = row_geometry(labels)
        if scale < 0.6:
            log(f"warning: profile '{name}' is crowded ({len(labels)} keys, "
                f"labels will be small)")

        rects, xml_keys = [], []
        for i, ((x, w), label) in enumerate(zip(geo, labels)):
            kid = "ESC" if i == 0 else f"okb{i}"
            rects.append(f'  <rect id="{kid}" x="{x:.4f}" y="{ROW_Y}" '
                         f'width="{w:.4f}" height="{ROW_H}"/>')
            if i == 0:
                xml_keys.append(f'<key label_margin="{LABEL_MARGIN}" '
                                f'group="halfrow" id="ESC"/>')
            else:
                mod = action_module(keys[i - 1])
                xml_keys.append(f'<key label_margin="{LABEL_MARGIN}" '
                                f'group="halfrow" id="{kid}" '
                                f'label={quoteattr(label)} script="{mod}"/>')
        svg = ('<?xml version="1.0" encoding="UTF-8"?>\n'
               '<svg xmlns="http://www.w3.org/2000/svg" width="318" height="96">\n'
               + "\n".join(rects) + "\n</svg>\n")
        h = hashlib.sha1((svg + "".join(xml_keys) + src_key).encode()).hexdigest()[:8]
        svg_path = os.path.join(GEN_DIR, f"{name}.{h}.svg")
        lay_path = os.path.join(GEN_DIR, f"{name}.{h}.onboard")
        panel = ('<panel filename=' + quoteattr(svg_path) + '>\n            '
                 + "\n            ".join(xml_keys) + '\n          </panel>')
        out = HALF_ROW_RE.sub(lambda m: m.group(1) + panel, src, count=1)
        for p, data in ((svg_path, svg), (lay_path, out)):
            if not os.path.exists(p):
                with open(p, "w", encoding="utf-8") as f:
                    f.write(data)
        index[name] = lay_path
        keep |= {svg_path, lay_path}

    for p in glob.glob(os.path.join(GEN_DIR, "*.onboard")) + \
             glob.glob(os.path.join(GEN_DIR, "*.svg")):
        if p not in keep:
            os.remove(p)
    with open(STATE, "w") as f:
        json.dump(index, f, indent=1)
    return index


# --------------------------------------------------------------- detection

def xprop(win, *props):
    try:
        out = subprocess.run(["xprop", "-id", win, *props], capture_output=True,
                             text=True, timeout=2).stdout
    except Exception:
        return {}
    res = {}
    m = re.search(r'WM_CLASS\(STRING\) = (.*)', out)
    if m:
        res["class"] = re.findall(r'"([^"]*)"', m.group(1))
    m = re.search(r'_NET_WM_PID\(CARDINAL\) = (\d+)', out)
    if m:
        res["pid"] = int(m.group(1))
    m = re.search(r'_NET_WM_NAME\(UTF8_STRING\) = "(.*)"', out)
    if m:
        res["title"] = m.group(1)
    return res


def active_window():
    out = subprocess.run(["xprop", "-root", "_NET_ACTIVE_WINDOW"],
                         capture_output=True, text=True).stdout
    m = re.search(r'(0x[0-9a-f]+)', out)
    return m.group(1) if m else None


def proc_stat(pid):
    with open(f"/proc/{pid}/stat") as f:
        rest = f.read().rsplit(")", 1)[1].split()
    # rest[0]=state [1]=ppid [2]=pgrp [3]=session [4]=tty_nr [5]=tpgid
    return int(rest[4]), int(rest[5])


def comm(pid):
    try:
        with open(f"/proc/{pid}/comm") as f:
            return f.read().strip()
    except OSError:
        return ""


def children(pid):
    kids = []
    for t in glob.glob(f"/proc/{pid}/task/*/children"):
        try:
            with open(t) as f:
                kids += [int(x) for x in f.read().split()]
        except OSError:
            pass
    return kids


def pty_mtime(pid):
    try:
        return os.stat(os.readlink(f"/proc/{pid}/fd/0")).st_mtime
    except OSError:
        return 0


def tmux_pane_command(client_pid):
    sock = []
    try:
        with open(f"/proc/{client_pid}/cmdline", "rb") as f:
            argv = f.read().decode(errors="replace").split("\0")
        for i, a in enumerate(argv):
            if a in ("-L", "-S") and i + 1 < len(argv):
                sock = [a, argv[i + 1]]
    except OSError:
        pass
    try:
        out = subprocess.run(["tmux", *sock, "list-clients", "-F",
                              "#{client_pid}\t#{pane_current_command}"],
                             capture_output=True, text=True, timeout=1).stdout
    except Exception:
        return None
    for line in out.splitlines():
        p, _, cmd = line.partition("\t")
        if p == str(client_pid):
            return cmd
    return None


def terminal_profile(cfg, pid):
    t = cfg["terminal"]
    shell = t.get("shell", "term-shell")
    cmds = t.get("commands", {})
    shells = [c for c in children(pid) if proc_stat(c)[0] != 0] if pid else []
    if not shells:
        return shell, "?"
    # several tabs in one process (e.g. xfce4-terminal): the active tab is
    # the one whose pty saw the most recent I/O
    sh = max(shells, key=pty_mtime)
    fg = proc_stat(sh)[1]
    name = comm(fg)
    if name.startswith("tmux"):
        inner = tmux_pane_command(fg) or ""
        return cmds.get(inner, t.get("tmux", shell)), f"tmux:{inner}"
    return cmds.get(name, shell), name


def profile_for(cfg, win):
    """-> (profile or None to keep current, is_terminal, info)"""
    if not win or win == "0x0":
        return None, False, "no window"
    p = xprop(win, "WM_CLASS", "_NET_WM_PID", "_NET_WM_NAME")
    classes = p.get("class", [])
    title = p.get("title", "")
    if any(c.lower().startswith("onboard") for c in classes) or \
       title.startswith("Onboard"):
        return None, False, "onboard"
    for rule in cfg["rules"]:
        rx = re.compile(rule["class"], re.I)
        if any(rx.search(c) for c in classes):
            if rule.get("terminal"):
                prof, inner = terminal_profile(cfg, p.get("pid"))
                return prof, True, f"{classes} [{inner}]"
            return rule["profile"], False, str(classes)
    return cfg["settings"].get("default_profile", "default"), False, str(classes)


# ------------------------------------------------------------------- watch

class Onboard:
    def __init__(self):
        from gi.repository import Gio
        self.s = Gio.Settings.new("org.onboard")

    def set_layout(self, path):
        if self.s.get_string("layout") != path:
            self.s.set_string("layout", path)
            self.s.sync()
            return True
        return False


def config_mtimes(cfg):
    base = base_layout_path(cfg)
    files = [CONFIG, base] + glob.glob(os.path.join(os.path.dirname(base), "*.svg"))
    return tuple(os.path.getmtime(f) for f in files if os.path.exists(f))


def watch():
    os.makedirs(os.path.dirname(LOCK), exist_ok=True)
    lock = open(LOCK, "w")
    try:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except OSError:
        sys.exit("okb: watcher already running")

    cfg = load_config()
    index = generate(cfg)
    mt = config_mtimes(cfg)
    ob = Onboard()
    log("watching; profiles:", ", ".join(index))

    spy = subprocess.Popen(["xprop", "-spy", "-root", "_NET_ACTIVE_WINDOW"],
                           stdout=subprocess.PIPE, text=True, bufsize=1)
    sel = selectors.DefaultSelector()
    sel.register(spy.stdout, selectors.EVENT_READ)

    win, is_term, current, last_cfg_check = active_window(), False, None, 0
    dirty = True
    while True:
        timeout = 0.4 if is_term else 2.0
        for _key, _ in sel.select(timeout):
            line = spy.stdout.readline()
            if not line:
                sys.exit("okb: xprop -spy exited")
            m = re.search(r'(0x[0-9a-f]+)', line)
            if m and m.group(1) != win:
                win, dirty = m.group(1), True

        now = time.monotonic()
        if now - last_cfg_check > 2:
            last_cfg_check = now
            try:
                new_mt = config_mtimes(cfg)
                if new_mt != mt:
                    cfg = load_config()
                    index = generate(cfg)
                    mt = config_mtimes(cfg)
                    current, dirty = None, True    # force re-apply
                    log("config changed, regenerated")
            except Exception as ex:
                log("config error (keeping previous):", ex)

        if not (dirty or is_term):
            continue
        dirty = False
        try:
            prof, term, info = profile_for(cfg, win)
        except Exception as ex:
            log("detect error:", ex)
            continue
        if prof is None:
            continue
        is_term = term
        if prof not in index:
            log(f"unknown profile '{prof}' for {info}")
            prof = cfg["settings"].get("default_profile", "default")
        if prof != current or ob.s.get_string("layout") != index[prof]:
            if ob.set_layout(index[prof]):
                log(f"-> {prof:12} {info}")
            current = prof


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "watch"
    if cmd == "generate":
        for k, v in generate().items():
            print(f"{k:12} {v}")
    elif cmd == "status":
        cfg = load_config()
        print(profile_for(cfg, active_window()))
    elif cmd == "watch":
        watch()
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
